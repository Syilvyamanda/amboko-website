USE amboko_erp;
SET FOREIGN_KEY_CHECKS = 0;
SET NAMES utf8mb4;

-- ---------- kolom tambahan di tabel yang sudah ada ----------
ALTER TABLE users
    MODIFY email VARCHAR(100) NULL,
    ADD COLUMN IF NOT EXISTS channel ENUM('online','offline') NOT NULL DEFAULT 'online',
    ADD COLUMN IF NOT EXISTS permissions VARCHAR(255) NULL;
ALTER TABLE categories ADD COLUMN IF NOT EXISTS image_url VARCHAR(255) NULL;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS channel ENUM('online','offline') NOT NULL DEFAULT 'online';
ALTER TABLE payments MODIFY method ENUM('qris','va','card','cash') NOT NULL;

-- ---------- tabel baru ----------
CREATE TABLE IF NOT EXISTS shipping_methods (
    id        INT AUTO_INCREMENT PRIMARY KEY,
    name      VARCHAR(60) NOT NULL,
    cost      INT NOT NULL DEFAULT 0,
    free_min  INT NULL,
    estimate  VARCHAR(40) NULL,
    note      VARCHAR(120) NULL,
    is_active TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS payment_methods (
    id        INT AUTO_INCREMENT PRIMARY KEY,
    name      VARCHAR(60) NOT NULL,
    type      ENUM('qris','va','card','cash') NOT NULL,
    detail    VARCHAR(120) NULL,
    is_active TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS order_returns (
    id            INT AUTO_INCREMENT PRIMARY KEY,
    code          VARCHAR(20) NOT NULL UNIQUE,
    order_id      INT NOT NULL,
    product_name  VARCHAR(150) NOT NULL,
    type          ENUM('return','exchange') NOT NULL,
    reason        VARCHAR(160) NOT NULL,
    detail        VARCHAR(160) NULL,
    status        ENUM('requested','approved','processing','done','rejected') NOT NULL DEFAULT 'requested',
    refund_amount DECIMAL(14,2) NOT NULL DEFAULT 0,
    admin_note    VARCHAR(255) NULL,
    created_at    DATETIME NOT NULL,
    updated_at    DATETIME NOT NULL,
    CONSTRAINT fk_ret_order FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS expenses (
    id       INT AUTO_INCREMENT PRIMARY KEY,
    spent_at DATE NOT NULL,
    category VARCHAR(40) NOT NULL,
    note     VARCHAR(150) NULL,
    amount   INT NOT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS crm_leads (
    id         INT AUTO_INCREMENT PRIMARY KEY,
    name       VARCHAR(100) NOT NULL,
    phone      VARCHAR(30) NULL,
    source     VARCHAR(30) NOT NULL,
    interest   VARCHAR(100) NULL,
    status     ENUM('new','contacted','interested','won','lost') NOT NULL DEFAULT 'new',
    note       VARCHAR(255) NULL,
    created_at DATETIME NOT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS crm_interactions (
    id         INT AUTO_INCREMENT PRIMARY KEY,
    user_id    INT NULL,
    lead_id    INT NULL,
    type       ENUM('whatsapp','instagram','phone','store','email') NOT NULL,
    summary    VARCHAR(255) NOT NULL,
    created_at DATETIME NOT NULL,
    CONSTRAINT fk_ci_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_ci_lead FOREIGN KEY (lead_id) REFERENCES crm_leads(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS site_settings (
    k VARCHAR(40) PRIMARY KEY,
    v TEXT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS visitor_stats (
    stat_date     DATE PRIMARY KEY,
    visitors      INT NOT NULL DEFAULT 0,
    page_views    INT NOT NULL DEFAULT 0,
    src_instagram INT NOT NULL DEFAULT 0,
    src_tiktok    INT NOT NULL DEFAULT 0,
    src_search    INT NOT NULL DEFAULT 0,
    src_direct    INT NOT NULL DEFAULT 0
) ENGINE=InnoDB;

